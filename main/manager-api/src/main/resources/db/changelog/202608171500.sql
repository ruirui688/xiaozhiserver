CREATE TABLE `ai_reception_customer_profile` (
  `id` VARCHAR(32) NOT NULL COMMENT '接待档案ID',
  `workspace_id` VARCHAR(32) NOT NULL COMMENT '所属工作空间ID',
  `person_id` VARCHAR(32) NOT NULL COMMENT '人物档案ID',
  `customer_stage` VARCHAR(16) NOT NULL DEFAULT 'NEW' COMMENT 'NEW/RETURNING/LONG_TERM/VIP',
  `company_name` VARCHAR(120) NULL COMMENT '已确认公司名称',
  `hobbies_json` JSON NULL COMMENT '已确认爱好',
  `food_preferences_json` JSON NULL COMMENT '口味预算套餐和忌口',
  `seat_preferences_json` JSON NULL COMMENT '座位偏好',
  `reception_notes` VARCHAR(500) NULL COMMENT '人工接待备注',
  `sensitive_notes` VARCHAR(500) NULL COMMENT '有同意范围的敏感需求',
  `consent_scope` VARCHAR(128) NOT NULL DEFAULT '' COMMENT '逗号分隔的允许用途',
  `visit_count` INT NOT NULL DEFAULT 0 COMMENT '完成到访次数',
  `first_visit_at` DATETIME NULL,
  `last_visit_at` DATETIME NULL,
  `last_confirmed_at` DATETIME NULL COMMENT '最近人工或用户确认时间',
  `status` TINYINT NOT NULL DEFAULT 1,
  `creator` BIGINT NULL,
  `updater` BIGINT NULL,
  `create_date` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_date` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_reception_profile_person` (`person_id`),
  KEY `idx_reception_profile_workspace_stage` (`workspace_id`, `customer_stage`, `status`),
  CONSTRAINT `fk_reception_profile_person` FOREIGN KEY (`person_id`) REFERENCES `ai_person_profile` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='人物接待业务档案';

CREATE TABLE `ai_reception_appointment` (
  `id` VARCHAR(32) NOT NULL COMMENT '预约ID',
  `workspace_id` VARCHAR(32) NOT NULL,
  `person_id` VARCHAR(32) NOT NULL,
  `start_at` DATETIME NOT NULL,
  `end_at` DATETIME NOT NULL,
  `party_size` INT NOT NULL DEFAULT 1,
  `status` VARCHAR(16) NOT NULL DEFAULT 'CONFIRMED' COMMENT 'PENDING/CONFIRMED/ARRIVED/CANCELLED/COMPLETED/NO_SHOW',
  `seat_request` VARCHAR(200) NULL,
  `notes` VARCHAR(500) NULL,
  `creator` BIGINT NULL,
  `updater` BIGINT NULL,
  `create_date` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_date` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_reception_appointment_workspace_time` (`workspace_id`, `start_at`, `end_at`),
  KEY `idx_reception_appointment_person_time` (`person_id`, `start_at`),
  CONSTRAINT `fk_reception_appointment_person` FOREIGN KEY (`person_id`) REFERENCES `ai_person_profile` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='门口接待预约';

CREATE TABLE `ai_reception_visit_event` (
  `id` VARCHAR(32) NOT NULL,
  `workspace_id` VARCHAR(32) NOT NULL,
  `device_id` VARCHAR(32) NOT NULL,
  `device_event_id` VARCHAR(128) NOT NULL,
  `group_session_id` VARCHAR(128) NOT NULL,
  `scene_epoch` BIGINT NOT NULL DEFAULT 0,
  `event_type` VARCHAR(32) NOT NULL,
  `selected_person_ids_json` JSON NULL,
  `present_count` INT NOT NULL DEFAULT 0,
  `decision_reason` VARCHAR(128) NULL,
  `captured_at` DATETIME NULL,
  `decision_at` DATETIME NULL,
  `create_date` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_reception_visit_device_event` (`device_id`, `device_event_id`),
  KEY `idx_reception_visit_workspace_time` (`workspace_id`, `create_date`),
  CONSTRAINT `fk_reception_visit_device` FOREIGN KEY (`device_id`) REFERENCES `ai_device` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='接待流程审计事件';
