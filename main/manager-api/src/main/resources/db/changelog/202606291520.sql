CREATE TABLE IF NOT EXISTS ai_memory_source_event (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    event_id VARCHAR(64) NOT NULL COMMENT '事件ID',
    agent_id VARCHAR(64) NOT NULL COMMENT '智能体ID',
    user_id BIGINT NULL COMMENT '所属用户ID',
    mac_address VARCHAR(64) NULL COMMENT '设备MAC地址',
    session_id VARCHAR(64) NULL COMMENT '会话ID',
    scope_type VARCHAR(32) NOT NULL DEFAULT 'device' COMMENT '作用域类型',
    scope_id VARCHAR(128) NOT NULL COMMENT '作用域ID',
    speaker_id VARCHAR(128) NULL COMMENT '说话人ID',
    event_type VARCHAR(64) NOT NULL COMMENT '事件类型',
    chat_type TINYINT NULL COMMENT '聊天类型',
    content_text TEXT NULL COMMENT '事件文本',
    content_json JSON NULL COMMENT '事件JSON',
    pii_level VARCHAR(32) NOT NULL DEFAULT 'normal' COMMENT '敏感级别',
    source_timestamp DATETIME NULL COMMENT '来源时间',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_ai_memory_source_event_event_id (event_id),
    KEY idx_ai_memory_source_event_agent_scope (agent_id, scope_type, scope_id),
    KEY idx_ai_memory_source_event_session (session_id),
    KEY idx_ai_memory_source_event_created_at (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='长期记忆原始事件证据层';

CREATE TABLE IF NOT EXISTS ai_memory_candidate (
