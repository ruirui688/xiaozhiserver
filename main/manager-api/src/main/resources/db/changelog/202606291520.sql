CREATE TABLE IF NOT EXISTS ai_memory_fact (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    memory_id VARCHAR(64) NOT NULL COMMENT '记忆ID',
    agent_id VARCHAR(64) NOT NULL COMMENT '智能体ID',
    user_id BIGINT NULL COMMENT '所属用户ID',
    mac_address VARCHAR(64) NULL COMMENT '设备MAC地址',
    scope_type VARCHAR(32) NOT NULL DEFAULT 'device' COMMENT '作用域类型',
    scope_id VARCHAR(128) NOT NULL COMMENT '作用域ID',
    memory_type VARCHAR(64) NOT NULL COMMENT '记忆类型',
    category VARCHAR(64) NOT NULL DEFAULT 'general' COMMENT '分类',
    canonical_text TEXT NOT NULL COMMENT '标准文本',
    payload JSON NULL COMMENT '结构化内容',
    importance DECIMAL(4,3) NOT NULL DEFAULT 0.500 COMMENT '重要性',
    confidence DECIMAL(4,3) NOT NULL DEFAULT 0.500 COMMENT '置信度',
    sensitivity VARCHAR(32) NOT NULL DEFAULT 'normal' COMMENT '敏感级别',
    confirmation_state VARCHAR(32) NOT NULL DEFAULT 'auto' COMMENT '确认状态',
    status VARCHAR(32) NOT NULL DEFAULT 'active' COMMENT '状态',
    valid_from DATETIME NULL COMMENT '生效时间',
    valid_to DATETIME NULL COMMENT '失效时间',
    first_seen_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '首次出现时间',
    last_seen_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '最近出现时间',
    expires_at DATETIME NULL COMMENT '过期时间',
    archived_at DATETIME NULL COMMENT '归档时间',
    source_event_id VARCHAR(64) NULL COMMENT '来源事件ID',
    source_hash VARCHAR(128) NULL COMMENT '来源哈希',
    extractor_version VARCHAR(64) NULL COMMENT '抽取器版本',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_ai_memory_fact_memory_id (memory_id),
    KEY idx_ai_memory_fact_agent_scope_status (agent_id, scope_type, scope_id, status),
    KEY idx_ai_memory_fact_agent_type_status (agent_id, memory_type, status),
    KEY idx_ai_memory_fact_updated_at (updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='长期事实记忆主表';

