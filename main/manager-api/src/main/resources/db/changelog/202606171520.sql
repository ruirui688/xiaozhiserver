CREATE TABLE IF NOT EXISTS `ai_model_benchmark_task` (
  `id` varchar(32) NOT NULL COMMENT '任务ID',
  `model_type` varchar(32) DEFAULT NULL COMMENT '模型类型',
  `model_ids` text COMMENT '模型ID列表JSON',
  `iterations` int DEFAULT 3 COMMENT '每模型测试轮数',
  `concurrency` int DEFAULT 3 COMMENT '并发模型数',
  `status` varchar(32) NOT NULL DEFAULT 'PENDING' COMMENT '任务状态',
  `progress` int NOT NULL DEFAULT 0 COMMENT '进度百分比',
  `summary` varchar(1000) DEFAULT NULL COMMENT '摘要',
  `error_message` text COMMENT '错误信息',
  `started_at` datetime DEFAULT NULL COMMENT '开始时间',
  `finished_at` datetime DEFAULT NULL COMMENT '结束时间',
  `duration_ms` bigint DEFAULT NULL COMMENT '总耗时毫秒',
  `metric_notes` text COMMENT '指标说明JSON',
  `creator` bigint DEFAULT NULL COMMENT '创建者',
  `create_date` datetime DEFAULT NULL COMMENT '创建时间',
  `updater` bigint DEFAULT NULL COMMENT '更新者',
  `update_date` datetime DEFAULT NULL COMMENT '更新时间',
  PRIMARY KEY (`id`),
  KEY `idx_model_benchmark_task_status` (`status`),
  KEY `idx_model_benchmark_task_create_date` (`create_date`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='模型专业评测任务';

CREATE TABLE IF NOT EXISTS `ai_model_benchmark_result` (
  `id` varchar(32) NOT NULL COMMENT '结果ID',
  `task_id` varchar(32) NOT NULL COMMENT '任务ID',
  `model_id` varchar(32) NOT NULL COMMENT '模型ID',
  `model_name` varchar(255) DEFAULT NULL COMMENT '模型名称',
  `model_type` varchar(32) DEFAULT NULL COMMENT '模型类型',
  `provider_type` varchar(64) DEFAULT NULL COMMENT '供应器类型',
  `benchmark_level` varchar(32) DEFAULT NULL COMMENT '评测级别',
  `benchmark_level_text` varchar(64) DEFAULT NULL COMMENT '评测级别说明',
  `success_count` int DEFAULT 0 COMMENT '成功次数',
  `failure_count` int DEFAULT 0 COMMENT '失败次数',
  `success_rate` double DEFAULT 0 COMMENT '成功率',
  `avg_latency_ms` double DEFAULT NULL COMMENT '平均延时毫秒',
  `p50_latency_ms` bigint DEFAULT NULL COMMENT 'P50延时毫秒',
  `p90_latency_ms` bigint DEFAULT NULL COMMENT 'P90延时毫秒',
  `p95_latency_ms` bigint DEFAULT NULL COMMENT 'P95延时毫秒',
  `tokens_per_second` double DEFAULT NULL COMMENT 'tokens/s',
  `ttft_ms` bigint DEFAULT NULL COMMENT '首token耗时毫秒',
  `first_audio_ms` bigint DEFAULT NULL COMMENT '首音频耗时毫秒',
  `rtf` double DEFAULT NULL COMMENT 'Real Time Factor',
  `cer` double DEFAULT NULL COMMENT '字符错误率',
  `wer` double DEFAULT NULL COMMENT '词错误率',
  `quality_score` double DEFAULT NULL COMMENT '质量评分',
  `logic_score` double DEFAULT NULL COMMENT '逻辑性评分',
  `context_score` double DEFAULT NULL COMMENT '上下文评分',
  `summary` varchar(1000) DEFAULT NULL COMMENT '摘要',
  `error_summary` text COMMENT '错误摘要',
  `create_date` datetime DEFAULT NULL COMMENT '创建时间',
  PRIMARY KEY (`id`),
  KEY `idx_model_benchmark_result_task` (`task_id`),
  KEY `idx_model_benchmark_result_model` (`model_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='模型专业评测结果';

